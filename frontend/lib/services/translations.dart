/// Traduce un síntoma al español. Si no hay traducción exacta, formatea el inglés.
String translateSymptom(String englishSymptom) {
  return symptomTranslations[englishSymptom] ?? _formatEnglish(englishSymptom);
}

/// Traduce una enfermedad al español con múltiples estrategias de fallback.
String translateDisease(String englishDisease) {
  // 1. Coincidencia exacta
  if (diseaseTranslations.containsKey(englishDisease)) {
    return diseaseTranslations[englishDisease]!;
  }

  // 2. Trim + coincidencia exacta (espacios extra)
  final trimmed = englishDisease.trim();
  if (diseaseTranslations.containsKey(trimmed)) {
    return diseaseTranslations[trimmed]!;
  }

  // 3. Búsqueda case-insensitive
  final lower = trimmed.toLowerCase();
  for (final entry in diseaseTranslations.entries) {
    if (entry.key.toLowerCase() == lower) return entry.value;
  }

  // 4. Búsqueda parcial: si la clave está contenida en el nombre
  for (final entry in diseaseTranslations.entries) {
    if (lower.contains(entry.key.toLowerCase()) && entry.key.length > 4) {
      return entry.value;
    }
  }

  // 5. Fallback: formatear el nombre en inglés
  return _formatEnglish(trimmed);
}

String _formatEnglish(String text) {
  return text
      .replaceAll('_', ' ')
      .replaceAll('  ', ' ')
      .trim()
      .split(' ')
      .map((w) => w.isNotEmpty ? '${w[0].toUpperCase()}${w.substring(1)}' : '')
      .join(' ');
}